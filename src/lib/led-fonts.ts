/**
 * Bitmap fonts for LED matrix displays.
 *
 * An LED matrix has no character cells — text exists only because a bitmap
 * font was drawn into its pixels. These are the two sizes the hardware
 * actually ships with: a 3×5 face (TomThumb-class; AWTRIX, Pixlet, Adafruit
 * GFX) for 8-pixel-tall clocks, and the classic 5×7 face (HD44780 / hzeller
 * `5x7.bdf`-class) for HUB75 panels.
 *
 * Glyphs are written as rows of `#` (lit) and `.` (off) so a reviewer can see
 * the letter in the source. They cover the whole split-flap character set
 * (BOARD_CHARS in ./board-characters) plus `♥`, because an LED board renders
 * the same message markup a split-flap board does; a character with no glyph
 * draws as blank, the same way an unknown character becomes code 0 on a flap.
 *
 * Beyond the flap set, each face carries lowercase a–z (used only when a
 * layout asks for `letterCase: "mixed"`; the default uppercases like the flap)
 * and the icons of ./board-icons. The 3×5 lowercase follows Tom Thumb's idea —
 * x-height one row below the caps, descenders folded into the box — and the
 * 5×7 lowercase is the HD44780 ROM's. Icons are per-face and optional: a face
 * without a glyph for an icon draws the icon's split-flap fallback instead.
 */

import type { BoardIconName } from "./board-icons";

export type LedFontId = "3x5" | "5x7";

export interface LedFont {
  id: LedFontId;
  /** Glyph box width in pixels. */
  glyphWidth: number;
  /** Glyph box height in pixels. */
  glyphHeight: number;
  /** Blank pixels between adjacent glyphs. */
  spacingX: number;
  /** Blank pixels between text rows. */
  spacingY: number;
  /** Glyph rows, top to bottom; each string is `glyphWidth` of `#`/`.`. */
  glyphs: Readonly<Record<string, readonly string[]>>;
  /** Icon glyphs, same shape as `glyphs`. Missing icons draw their fallback. */
  icons: Readonly<Partial<Record<BoardIconName, readonly string[]>>>;
}

